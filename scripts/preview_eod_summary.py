"""Read-only EOD preview; no notifications, orders or journal writes."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from eod_summary import BASE, build_summary


def preview(config, *, base=BASE, now=None, broker=None):
    import csv
    import json
    from eod_summary import _today, PACIFIC
    from datetime import datetime
    today = (now or datetime.now(PACIFIC)).astimezone(PACIFIC).date()
    account, positions, source = {}, [], "unavailable (n/a)"
    if broker is not None and getattr(broker, "trading_client", None) and getattr(broker, "paper", False):
        try:
            account, positions = broker.get_account(), broker.get_positions()
            source = "read-only paper broker"
        except Exception:
            source = "broker unavailable; journal fallback"
    if not account:
        path = Path(base) / "journal" / "equity_curve.csv"
        if path.exists():
            with path.open(newline="") as f:
                rows = list(csv.DictReader(f))
            if rows:
                rows.sort(key=lambda r: r.get("date", ""))
                account = {"equity": rows[-1].get("equity"),
                           "last_equity": rows[-2].get("equity") if len(rows) > 1 else None}
                source = "journal equity snapshot (positions/cash n/a)"
    rd = {}
    readiness_path = Path(base) / "learning" / "readiness_state.json"
    state_path = Path(base) / "journal" / "etf_state.json"
    state = json.loads(state_path.read_text()) if state_path.exists() else {}
    if readiness_path.exists():
        saved = json.loads(readiness_path.read_text())
        current_label = state.get("strategy_version")
        same_strategy = (saved.get("strategy_version") == current_label
                         if saved.get("strategy_version") is not None
                         else saved.get("mode") == config.get("strategy", {}).get("mode"))
        if _today(saved.get("updated_at"), today) and same_strategy:
            rd = saved
    spy_history = None
    spy_closes = None
    if broker is not None and getattr(broker, "paper", False) and hasattr(broker, "fetch_yf_history"):
        try:
            bars = broker.fetch_yf_history("SPY", period="2y", interval="1d")
            if bars is not None and len(bars) >= 2:
                spy_closes = tuple(bars["Close"].iloc[-2:])
                spy_history = {str(index.date()): value for index, value in bars["Close"].items()}
        except Exception:
            pass
    summary = build_summary(config, account, positions, rd, base=base, now=now,
                            spy_history=spy_history, spy_closes=spy_closes)
    legacy = ["📊 Paper bot today"]
    if source == "read-only paper broker":
        equity = float(account.get("equity") or 0)
        prior = float(account.get("last_equity") or 0)
        legacy.extend((f"💰 Account ${equity:,.0f} · today {equity - prior:+,.0f}",
                       f"📦 {len(positions)} holdings"))
    else:
        legacy.append("⚠️ Account unavailable. Check the dashboard.")
    legacy.append("📌 ETFs" if config.get("strategy", {}).get("mode") == "etf_trend" else "📌 Stocks")
    if rd:
        legacy.append("⚠️ Live trading: review needed" if rd.get("status") == "READY_FOR_REVIEW"
                      else "🔒 Paper only. Live trading not approved.")
    diagnostics = (f"Source: {source}; readiness {'saved today' if rd else 'n/a'}; "
                   f"SPY {'historical closes' if spy_history else 'n/a'}. "
                   "Chart attachment is not generated by this read-only preview.")
    return diagnostics + "\n" + summary + "\n\n" + "\n".join(legacy)


if __name__ == "__main__":
    import yaml
    base = Path(__file__).resolve().parent.parent
    from dotenv import load_dotenv
    import os
    load_dotenv(base / ".env", override=False)
    load_dotenv(os.getenv("HERMES_ENV_FILE", "/opt/data/.env"), override=False)
    with (base / "config.yaml").open() as f:
        config = yaml.safe_load(f)
    broker = None
    if (os.getenv("APCA_API_KEY_ID") and os.getenv("APCA_API_SECRET_KEY")
            and os.getenv("APCA_PAPER", "true").lower() == "true"):
        from data import DataProvider
        broker = DataProvider(paper=True)
    print(preview(config, base=base, broker=broker))
